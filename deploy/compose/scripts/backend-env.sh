#!/usr/bin/env bash
# Creates backend/.env (git-ignored) pointing the API at the local dev stack, using the secrets
# that `make dev-init` generated in deploy/compose/.env. Never overwrites an existing file.
set -euo pipefail

root="$(cd "$(dirname "$0")/../../.." && pwd)"
stack_env="$root/deploy/compose/.env"
target="$root/backend/.env"

if [[ -f "$target" ]]; then
  echo "backend/.env already exists; leaving it unchanged."
  exit 0
fi
if [[ ! -f "$stack_env" ]]; then
  echo "deploy/compose/.env is missing; run 'make dev-init' first." >&2
  exit 1
fi
set -a
# shellcheck disable=SC1090
source "$stack_env"
set +a

umask 077
cat >"$target" <<EOF
# Generated by 'make backend-env' from deploy/compose/.env. Local development only.
SUPPORTX_PROFILE=dev
# The app connects as supportx_app through PgBouncer (RLS applies; CLAUDE.md rule a).
SUPPORTX_DATABASE_URL=postgresql://supportx_app:${SUPPORTX_APP_PASSWORD}@127.0.0.1:${PGBOUNCER_PORT}/supportx
SUPPORTX_VALKEY_URL=valkey://:${VALKEY_PASSWORD}@127.0.0.1:${VALKEY_PORT}/0
SUPPORTX_NATS_URL=nats://127.0.0.1:${NATS_PORT}
EOF
echo "Created backend/.env for the local dev stack."
