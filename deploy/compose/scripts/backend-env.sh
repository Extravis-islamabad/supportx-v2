#!/usr/bin/env bash
# Writes backend/.env (git-ignored) pointing the API at the local dev stack, using the secrets
# that `make dev-init` generated in deploy/compose/.env. Never overwrites a value: if the file
# exists, only keys it does not have yet are appended (so new settings arrive without losing edits).
set -euo pipefail

root="$(cd "$(dirname "$0")/../../.." && pwd)"
stack_env="$root/deploy/compose/.env"
target="$root/backend/.env"

if [[ ! -f "$stack_env" ]]; then
  echo "deploy/compose/.env is missing; run 'make dev-init' first." >&2
  exit 1
fi
set -a
# shellcheck disable=SC1090
source "$stack_env"
set +a

values=(
  "SUPPORTX_PROFILE=dev"
  # The API connects as supportx_app through PgBouncer (RLS applies; CLAUDE.md rule a).
  "SUPPORTX_DATABASE_URL=postgresql://supportx_app:${SUPPORTX_APP_PASSWORD}@127.0.0.1:${PGBOUNCER_PORT}/supportx"
  # Migrations and dev tooling connect as supportx_migrator straight to PostgreSQL.
  "SUPPORTX_MIGRATION_DATABASE_URL=postgresql://supportx_migrator:${SUPPORTX_MIGRATOR_PASSWORD}@127.0.0.1:${POSTGRES_PORT}/supportx"
  # The outbox relay connects as supportx_relay straight to PostgreSQL (LISTEN/NOTIFY; WP-007).
  "SUPPORTX_RELAY_DATABASE_URL=postgresql://supportx_relay:${SUPPORTX_RELAY_PASSWORD}@127.0.0.1:${POSTGRES_PORT}/supportx"
  "SUPPORTX_VALKEY_URL=valkey://:${VALKEY_PASSWORD}@127.0.0.1:${VALKEY_PORT}/0"
  "SUPPORTX_NATS_URL=nats://127.0.0.1:${NATS_PORT}"
  # Login (WP-006): the supportx realm and its confidential console/portal clients.
  "SUPPORTX_OIDC_ISSUER=http://localhost:${KEYCLOAK_PORT}/realms/supportx"
  "SUPPORTX_OIDC_CONSOLE_CLIENT_SECRET=${KEYCLOAK_CONSOLE_CLIENT_SECRET}"
  "SUPPORTX_OIDC_PORTAL_CLIENT_SECRET=${KEYCLOAK_PORTAL_CLIENT_SECRET}"
  "SUPPORTX_SESSION_SECRET=${SESSION_SECRET}"
  # Realtime (WP-011): Centrifugo's server API and the key its client tokens are signed with.
  "SUPPORTX_CENTRIFUGO_API_URL=http://127.0.0.1:${CENTRIFUGO_PORT}"
  "SUPPORTX_CENTRIFUGO_API_KEY=${CENTRIFUGO_API_KEY}"
  "SUPPORTX_CENTRIFUGO_TOKEN_SECRET=${CENTRIFUGO_TOKEN_HMAC_SECRET}"
  # Object storage (WP-018): the dev stack's MinIO through the S3 API (D-016).
  "SUPPORTX_OBJECT_STORAGE_ENDPOINT=http://127.0.0.1:${MINIO_API_PORT}"
  "SUPPORTX_OBJECT_STORAGE_ACCESS_KEY=${MINIO_ROOT_USER}"
  "SUPPORTX_OBJECT_STORAGE_SECRET_KEY=${MINIO_ROOT_PASSWORD}"
  # Audit anchors (ADR-027): a dev-only signing key derived from the dev session secret.
  "SUPPORTX_AUDIT_SIGNING_KEY=dev-1:$(printf '%s' "audit-anchor:${SESSION_SECRET}" | openssl dgst -sha256 -binary | base64)"
)

umask 077
if [[ ! -f "$target" ]]; then
  echo "# Generated by 'make backend-env' from deploy/compose/.env. Local development only." >"$target"
  created=1
fi
added=0
for line in "${values[@]}"; do
  key="${line%%=*}"
  if ! grep -q "^${key}=" "$target"; then
    echo "$line" >>"$target"
    added=$((added + 1))
  fi
done
if [[ -n "${created:-}" ]]; then
  echo "Created backend/.env for the local dev stack."
elif ((added > 0)); then
  echo "backend/.env: added ${added} missing setting(s); existing values left unchanged."
else
  echo "backend/.env is up to date; left unchanged."
fi
