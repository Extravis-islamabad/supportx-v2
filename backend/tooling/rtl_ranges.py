"""The code points whose bidi class is R or AL, as ranges, for the console (isolation rule).

The server tests "contains right-to-left letters" with Python's own Unicode data
(`unicodedata.bidirectional(c) in {"R", "AL"}`); JavaScript regular expressions cannot ask for a
bidi class, so the console reads these ranges instead. `make labels-json` writes them, and
backend/tests/test_label_isolation.py fails when the file and Python's data differ.

    uv run python -m tooling.rtl_ranges <output.json>
"""

import json
import sys
import unicodedata
from pathlib import Path

RTL_CLASSES = frozenset({"R", "AL"})


def rtl_ranges() -> list[list[int]]:
    """[first, last] pairs (inclusive) of every code point with bidi class R or AL."""
    ranges: list[list[int]] = []
    for code in range(sys.maxunicode + 1):
        if unicodedata.bidirectional(chr(code)) not in RTL_CLASSES:
            continue
        if ranges and ranges[-1][1] == code - 1:
            ranges[-1][1] = code
        else:
            ranges.append([code, code])
    return ranges


def document() -> dict[str, object]:
    """The file's content."""
    return {
        "//": "Generated by `make labels-json` (backend/tooling/rtl_ranges.py): code points "
        "with bidi class R or AL, Unicode " + unicodedata.unidata_version + ".",
        "unicode": unicodedata.unidata_version,
        "ranges": rtl_ranges(),
    }


def main() -> None:
    """Write the ranges file."""
    Path(sys.argv[1]).write_text(json.dumps(document(), indent=1) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
