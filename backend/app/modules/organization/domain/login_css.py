"""The sign-in page's stylesheet (keycloak.v2 + brand colours and logo), one template for all.

`tooling/brand_assets.py` writes the SupportX default into the Keycloak theme; the public branding
route serves the same stylesheet per tenant (WP-017, REQ-SEC-003), with the tenant's colours and
logo URLs. Only the variables differ, so a Keycloak upgrade is checked once.
"""

from dataclasses import dataclass

from app.modules.organization.domain.branding import Colours


@dataclass(frozen=True)
class LoginLogos:
    """Logo URLs for the light, dark and high-contrast sign-in page."""

    logo: str
    logo_on_dark: str
    logo_high_contrast: str


LOGIN_CSS = """\
/* Generated by backend/tooling/brand_assets.py from frontend/packages/ui/src/brand/palette.json.
   Do not edit: run `make brand-assets`. SupportX colours and logo on the keycloak.v2 login page
   (light, dark through keycloak.v2's own dark-mode class, and high contrast). */
:root {{
  --keycloak-card-top-color: {primary};
  --pf-v5-global--primary-color--100: {primary};
  --pf-v5-global--primary-color--200: {hover};
  --pf-v5-global--link--Color: {primary};
  --pf-v5-global--link--Color--hover: {hover};
  --supportx-button: {primary};
  --supportx-button-hover: {hover};
  --supportx-card-top: linear-gradient(90deg, {gradient_start}, {gradient_end});
  --supportx-logo-url: url("{logo}");
}}
:root.pf-v5-theme-dark {{
  --pf-v5-global--primary-color--100: {primary};
  --pf-v5-global--primary-color--200: {hover};
  --pf-v5-global--link--Color: {dark_text};
  --pf-v5-global--link--Color--hover: {dark_text};
  --supportx-logo-url: url("{logo_on_dark}");
}}
/* High contrast on a light page: the one-colour logo and the darker primary. A dark page keeps
   the dark settings above (its link colour is already above 7:1). */
@media (prefers-contrast: more) {{
  :root:not(.pf-v5-theme-dark) {{
    --pf-v5-global--primary-color--100: {high_contrast};
    --pf-v5-global--primary-color--200: #000000;
    --pf-v5-global--link--Color: {high_contrast};
    --pf-v5-global--link--Color--hover: #000000;
    --supportx-button: {high_contrast};
    --supportx-button-hover: #000000;
    --supportx-card-top: linear-gradient(#000000, #000000);
    --supportx-logo-url: url("{logo_high_contrast}");
  }}
}}
.login-pf body {{
  background: #f5f5f5;
}}
:root.pf-v5-theme-dark.login-pf body {{
  background: #141414;
}}
.pf-v5-c-login__main-header {{
  border-top: 4px solid;
  border-image: var(--supportx-card-top) 1;
}}
.pf-v5-c-button.pf-m-primary {{
  --pf-v5-c-button--m-primary--BackgroundColor: var(--supportx-button);
  --pf-v5-c-button--m-primary--hover--BackgroundColor: var(--supportx-button-hover);
  --pf-v5-c-button--m-primary--focus--BackgroundColor: var(--supportx-button-hover);
  --pf-v5-c-button--m-primary--active--BackgroundColor: var(--supportx-button-hover);
  --pf-v5-c-button--m-primary--Color: #ffffff;
  --pf-v5-c-button--m-primary--hover--Color: #ffffff;
  --pf-v5-c-button--m-primary--focus--Color: #ffffff;
  --pf-v5-c-button--m-primary--active--Color: #ffffff;
}}
/* The realm name stays in the page for screen readers; the logo is drawn behind it. */
#kc-header-wrapper {{
  background: var(--supportx-logo-url) center / contain no-repeat;
  height: 48px;
  color: transparent !important;
  overflow: hidden;
}}
/* The organization's name under the logo (REQ-SEC-003), when Keycloak knows it: AA and more on
   the light (#f5f5f5), dark (#141414) and high-contrast page. */
.supportx-org-name {{
  margin: 8px 0 12px;
  text-align: center;
  font-size: 1.125rem;
  font-weight: 600;
  color: #262626;
  overflow-wrap: anywhere;
}}
:root.pf-v5-theme-dark .supportx-org-name {{
  color: #e6e6e6;
}}
@media (prefers-contrast: more) {{
  :root:not(.pf-v5-theme-dark) .supportx-org-name {{
    color: #000000;
  }}
}}
"""


def login_css(colours: Colours, logos: LoginLogos | None) -> str:
    """The stylesheet for `colours` and `logos`; without logos the theme's own logo stays."""
    if logos is None:
        css = LOGIN_CSS.format(
            primary=colours.primary,
            hover=colours.hover,
            dark_text=colours.dark_text,
            high_contrast=colours.high_contrast,
            gradient_start=colours.gradient[0],
            gradient_end=colours.gradient[1],
            logo="",
            logo_on_dark="",
            logo_high_contrast="",
        )
        return (
            "\n".join(line for line in css.splitlines() if "--supportx-logo-url" not in line) + "\n"
        )
    for url in (logos.logo, logos.logo_on_dark, logos.logo_high_contrast):
        if any(ch in url for ch in '"\\\n()'):
            raise ValueError(url)
    return LOGIN_CSS.format(
        primary=colours.primary,
        hover=colours.hover,
        dark_text=colours.dark_text,
        high_contrast=colours.high_contrast,
        gradient_start=colours.gradient[0],
        gradient_end=colours.gradient[1],
        logo=logos.logo,
        logo_on_dark=logos.logo_on_dark,
        logo_high_contrast=logos.logo_high_contrast,
    )
