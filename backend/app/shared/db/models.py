"""Declarative base, naming convention and column conventions (architecture.md §7.1; WP-005).

A tenant-scoped business table is declared as:

    class Ticket(TenantEntity):
        __tablename__ = "tickets"
        title: Mapped[str]
        __table_args__ = (Index(None, "tenant_id", "created_at"),)   # tenant_id first, always

and its migration calls `enable_tenant_rls("tickets")` (migrations/helpers.py). The guard in
tooling/rls_guard.py fails CI if either part is missing.
"""

import uuid
from datetime import UTC, datetime

from sqlalchemy import BigInteger, DateTime, ForeignKey, MetaData, func
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import DeclarativeBase, Mapped, declared_attr, mapped_column

from app.shared.ids import new_id

# Deterministic constraint/index names, so autogenerated migrations are stable and reviewable.
NAMING_CONVENTION = {
    "ix": "ix_%(table_name)s_%(column_0_N_name)s",
    "uq": "uq_%(table_name)s_%(column_0_N_name)s",
    "ck": "ck_%(table_name)s_%(constraint_name)s",
    "fk": "fk_%(table_name)s_%(column_0_N_name)s_%(referred_table_name)s",
    "pk": "pk_%(table_name)s",
}


class Base(DeclarativeBase):
    """Root of every ORM model in the Core API."""

    metadata = MetaData(naming_convention=NAMING_CONVENTION)
    type_annotation_map = {  # noqa: RUF012 - SQLAlchemy reads this class attribute as-is
        uuid.UUID: UUID(as_uuid=True),
        datetime: DateTime(timezone=True),  # timestamptz, always UTC (§7.1)
        int: BigInteger(),
    }


class UuidPrimaryKey:
    """UUIDv7 primary key, generated in the application (time-ordered, index-friendly)."""

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True, default=new_id, sort_order=-100)


class TenantScoped:
    """`tenant_id`, NOT NULL, referencing tenants. It must lead every composite index."""

    @declared_attr
    @classmethod
    def tenant_id(cls) -> Mapped[uuid.UUID]:
        """Owning tenant; RLS compares it with the transaction's `app.tenant_id`."""
        return mapped_column(
            ForeignKey("tenants.id", ondelete="RESTRICT"), nullable=False, sort_order=-90
        )


class TenantKeyed:
    """`tenant_id` as the first primary-key column (link tables: user_roles, members ...).

    Their composite primary key then starts with tenant_id, as the RLS guard requires of every
    multi-column index.
    """

    @declared_attr
    @classmethod
    def tenant_id(cls) -> Mapped[uuid.UUID]:
        """Owning tenant; leads the primary key."""
        return mapped_column(
            ForeignKey("tenants.id", ondelete="RESTRICT"), primary_key=True, sort_order=-90
        )


def utc_now() -> datetime:
    """`onupdate` for every `updated_at` column (also models that define their own)."""
    return datetime.now(UTC)


class Timestamps:
    """Creation and last-change time (timestamptz).

    Every update moves `updated_at` (ORM saves and bulk UPDATE statements alike), so a 409 can
    say when the save the user missed happened (QA WP-029 BUG-05). Computed in Python: a value
    the database computed would expire the attribute after the flush, and reading it again
    would need I/O the async session cannot do implicitly.
    """

    created_at: Mapped[datetime] = mapped_column(server_default=func.now(), sort_order=900)
    updated_at: Mapped[datetime] = mapped_column(
        server_default=func.now(), onupdate=utc_now, sort_order=901
    )


class Actors:
    """Who created and last changed the row (user IDs; NULL for system actions)."""

    created_by: Mapped[uuid.UUID | None] = mapped_column(sort_order=902)
    updated_by: Mapped[uuid.UUID | None] = mapped_column(sort_order=903)


class Versioned:
    """Optimistic-concurrency version (CLAUDE.md rule g); bumped by every update."""

    version: Mapped[int] = mapped_column(default=1, server_default="1", sort_order=904)


class SoftDeleted:
    """Soft delete marker; hard deletes happen only in GDPR erasure jobs (§7.1)."""

    deleted_at: Mapped[datetime | None] = mapped_column(sort_order=905)


class TenantEntity(UuidPrimaryKey, TenantScoped, Timestamps, Actors, Versioned, SoftDeleted, Base):
    """Base for every editable, tenant-scoped business record."""

    __abstract__ = True
