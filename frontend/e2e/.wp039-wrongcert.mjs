import { readFileSync } from 'node:fs';
import { chromium } from '@playwright/test';
const APP = 'http://localhost:5183';
const CERT = readFileSync('/private/tmp/claude-501/-Users-haiderzaidi-Extravis-supportx-v2/bae26076-1f7a-4867-9937-87165ed043a6/scratchpad/kc/wrongcert.txt', 'utf8');
const note = (s, ok, d = '') => console.log(`[${ok ? 'PASS' : 'FAIL'}] ${s} ${d}`);
const browser = await chromium.launch();
const admin = await (await browser.newContext()).newPage();
await admin.goto(`${APP}/admin/security`);
await admin.locator('#username').fill('admin@demo.test'); await admin.locator('#kc-login').click();
await admin.locator('#password').fill('Admin-Demo-2026!'); await admin.locator('#kc-login').click();
await admin.getByTestId('admin-security').waitFor();
await admin.getByTestId('sso-add').click();
const editor = admin.getByTestId('sso-editor');
await editor.getByTestId('sso-preset').getByText('SAML 2.0').click();
await editor.getByTestId('sso-display_name').fill('Wrong cert');
await editor.getByRole('combobox').fill('wrongcert.test,');
await editor.getByText('Enter the details by hand').click();
await editor.getByTestId('sso-sso_url').fill('http://127.0.0.1:28183/realms/samlidp/protocol/saml');
await editor.getByTestId('sso-certificate').fill(CERT);
await admin.getByTestId('sso-save').click();
const row = admin.getByTestId('sso-Wrong cert');
await row.waitFor({ timeout: 15000 });
note('saved with a valid but wrong certificate', true);
const [start] = await Promise.all([admin.waitForResponse((r) => r.url().includes('/tests') && r.request().method() === 'POST'), row.getByTestId('sso-test').click()]);
const url = (await start.json()).url;
const priv = await (await browser.newContext()).newPage();
await priv.goto(url);
await priv.locator('#username').fill('sam@samlcorp.test'); await priv.locator('#password').fill('Sam-Saml-2026!'); await priv.locator('#kc-login').click();
await priv.waitForTimeout(3000);
note('Keycloak shows its own error page in the private window', !priv.url().includes('sso-test-done'), (await priv.locator('body').innerText()).replace(/\n/g, ' ').slice(0, 160));
const dialog = admin.getByTestId('sso-test-dialog');
const failed = await dialog.getByTestId('sso-test-failed').waitFor({ timeout: 15000 }).then(() => true).catch(() => false);
note('the admin screen says why, in plain words', failed, (await dialog.innerText()).replace(/\n/g, ' / ').slice(0, 300));
await dialog.getByRole('button', { name: 'Close' }).first().click();
note('the set-up stays off (draft, cannot be switched on)', (await row.getByTestId('sso-state').innerText()) === 'Draft' && (await row.getByTestId('sso-switch').isDisabled()));
await browser.close();
